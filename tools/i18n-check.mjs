import { LANGS, t, setLang, isRtl, surahName, hasKey, getLang } from '../src/i18n.ts';
import assert from 'node:assert/strict';
assert.equal(LANGS.length, 13);
assert.deepEqual(LANGS.map((l) => l.code), ["az","tr","en","ar","ru","fr","id","bn","ms","ur","fa","es","de"]);
setLang("fa");
assert.equal(isRtl(), true);
assert.equal(surahName(1), "فاتحه");
assert.ok(t("miss.title").includes("ضعف") || t("miss.title") === "نقاط ضعف");
assert.ok(t("pill.today", { d: 3 }).includes("3"));
setLang("es");
assert.equal(isRtl(), false);
assert.equal(t("miss.export"), "Exportar");
assert.equal(surahName(114), "An-Nas");
setLang("de");
assert.equal(t("st.locateGo"), "Los");
assert.equal(surahName(1), "Al-Fatiha");
assert.ok(hasKey("miss.suggest"));
setLang("en");
assert.equal(t("miss.btn"), "Weak spots");
